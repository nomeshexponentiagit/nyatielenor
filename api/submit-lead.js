/**
 * Vercel Serverless Function — Nyati Elenor Lead Form Handler
 *
 * POST /api/submit-lead
 * Accepts lead form data and sends email notification to nomeshexponentia@gmail.com
 *
 * Environment variables required:
 *   SMTP_HOST  — SMTP server host (default: smtp.gmail.com)
 *   SMTP_PORT  — SMTP server port (default: 587)
 *   SMTP_USER  — SMTP username / email (sender)
 *   SMTP_PASS  — SMTP password or Gmail App Password
 *   NOTIFY_EMAIL — Recipient email (default: nomeshexponentia@gmail.com)
 *
 * For Gmail: Enable 2FA → Generate App Password at https://myaccount.google.com/apppasswords
 */

const nodemailer = require('nodemailer');

// CORS headers
const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'POST, OPTIONS',
  'Access-Control-Allow-Headers': 'Content-Type',
};

/**
 * Create transporter — reuses connection across warm invocations
 */
let transporter = null;

function getTransporter() {
  if (transporter) return transporter;

  transporter = nodemailer.createTransport({
    host: process.env.SMTP_HOST || 'smtp.gmail.com',
    port: parseInt(process.env.SMTP_PORT || '587', 10),
    secure: false,
    auth: {
      user: process.env.SMTP_USER || 'nomeshexponentia@gmail.com',
      pass: process.env.SMTP_PASS,
    },
  });

  return transporter;
}

