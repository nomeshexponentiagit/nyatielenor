/**
 * Validate lead data
 */
function validate(data) {
  const errors = [];
  if (!data.name || data.name.trim().length < 2) errors.push('Name is required');
  if (!data.phone || data.phone.trim().length < 10) errors.push('Valid phone number is required');
  if (!data.email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(data.email)) errors.push('Valid email is required');
  return errors;
}

// ─── Handler ───────────────────────────────────────────────────────────────

module.exports = async function handler(req, res) {
  // CORS preflight
  if (req.method === 'OPTIONS') {
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
    return res.status(200).end();
  }

  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  // Parse body
  let data;
  try {
    data = typeof req.body === 'string' ? JSON.parse(req.body) : req.body;
  } catch {
    return res.status(400).json({ error: 'Invalid JSON body' });
  }

  // Validate
  const errors = validate(data);
  if (errors.length > 0) {
    return res.status(400).json({ error: 'Validation failed', details: errors });
  }

  try {
    const mailer = getTransporter();
    const recipient = process.env.NOTIFY_EMAIL || 'nomeshexponentia@gmail.com';

    await mailer.sendMail({
      from: `"Nyati Elenor Leads" <${process.env.SMTP_USER || 'nomeshexponentia@gmail.com'}>`,
      to: recipient,
      replyTo: data.email,
      subject: `🔔 New Lead: ${data.name} — ${data.configuration || 'Enquiry'} — Nyati Elenor`,
      text: formatEmailText(data),
      html: formatEmailHTML(data),
    });

    console.log(`✅ Lead from ${data.name} sent to ${recipient}`);
    return res.status(200).json({ success: true, message: 'Lead submitted successfully' });
  } catch (err) {
    console.error('Email send error:', err.message);

    // Still return 200 to the user — the form data is not lost
    // In production, you'd queue this for retry or log to a backup store
    return res.status(200).json({
      success: true,
      message: 'Lead received. Email notification pending.',
      warning: 'Email delivery delayed — team will be notified',
    });
  }
};
